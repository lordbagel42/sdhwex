import type { MutationContext, QueryContext } from 'apps';
import { requirements } from './requirements.js';
import { ACCOUNT_ID, WORKER_NAME, FEED_URL, boundedJSON, feedHash, readLive, validateFeed, type Feed } from './feed.js';

export type ReadContext = QueryContext<typeof requirements>;
export type WriteContext = MutationContext<typeof requirements>;
type Lock = { operation_id: string | null; started_at: number | null };
type Publication = {
  id: string; state: string; action: string; before_hash: string; after_hash: string;
  before_json: string; after_json: string; started_at: number; finished_at: number | null; detail: string | null;
};

export function pendingOperation(ctx: ReadContext | WriteContext) {
  const lock = ctx.sql.exec<Lock>('SELECT operation_id, started_at FROM publish_lock WHERE slot = 1').one();
  return lock.operation_id ? { id: lock.operation_id, startedAt: lock.started_at } : null;
}

function finish(ctx: WriteContext, id: string, state: string, detail: string) {
  ctx.sql.transaction(() => {
    ctx.sql.exec('UPDATE publications SET state = ?, finished_at = ?, detail = ? WHERE id = ?',
      state, Date.now(), detail, id);
    ctx.sql.exec('UPDATE publish_lock SET operation_id = NULL, started_at = NULL WHERE slot = 1 AND operation_id = ?', id);
  });
}

export async function publish(ctx: WriteContext, expectedHash: string, action: string, change: (feed: Feed) => Feed) {
  if (!/^[a-f0-9]{64}$/.test(expectedHash)) throw new Error('Use the feedHash from a fresh read as expectedHash.');
  const handler = ctx.files.find(file => file.path === 'worker-handler.txt')?.content;
  if (!handler) throw new Error('The fixed Worker handler is missing from this app version.');
  const id = crypto.randomUUID();
  const reserved = ctx.sql.exec(
    'UPDATE publish_lock SET operation_id = ?, started_at = ? WHERE slot = 1 AND operation_id IS NULL',
    id, Date.now()).rowsWritten > 0;
  if (!reserved) throw new Error('Another publication is in progress or unresolved. Inspect status and resolvePending; do not retry a write.');
  let writeStarted = false;
  try {
    const before = await readLive(ctx);
    const beforeHash = await feedHash(before);
    if (beforeHash !== expectedHash) throw new Error('Feed changed since your read. Read it again and reconcile before publishing.');
    const latest = ctx.sql.exec<{ after_hash: string; finished_at: number }>(
      "SELECT after_hash, finished_at FROM publications WHERE state = 'uploaded' ORDER BY started_at DESC LIMIT 1").toArray()[0];
    if (latest && Date.now() - latest.finished_at < 6 * 60 * 1000 && latest.after_hash !== beforeHash)
      throw new Error('The previous publication has not propagated to this read yet. Wait, then read the live feed again.');
    const after = validateFeed(change(structuredClone(before)));
    const afterHash = await feedHash(after);
    if (beforeHash === afterHash) {
      ctx.sql.exec('UPDATE publish_lock SET operation_id = NULL, started_at = NULL WHERE operation_id = ?', id);
      return { changed: false, publicationId: '', feedHash: afterHash, feedUrl: FEED_URL, message: 'No change; nothing was uploaded.' };
    }
    const source = '// Generated by sdhwex Manager. Remote JSON only; extension code is not hosted here.\n' +
      'const TRIAGE_DATA = ' + JSON.stringify(after) + ';\n' + handler;
    ctx.sql.exec(
      'INSERT INTO publications (id, state, action, before_hash, after_hash, before_json, after_json, started_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
      id, 'uploading', action, beforeHash, afterHash, JSON.stringify(before), JSON.stringify(after), Date.now());
    const account = ctx.user.accounts.cloudflare;
    writeStarted = true;
    const response = await ctx.fetch(
      'https://api.cloudflare.com/client/v4/accounts/' + ACCOUNT_ID + '/workers/scripts/' + WORKER_NAME, {
        method: 'PUT', redirect: 'manual',
        signal: AbortSignal.any([ctx.signal, AbortSignal.timeout(45000)]),
        headers: { ...account.headers(), 'X-Auth-Email': account.fields.email,
          'Content-Type': 'application/javascript', Accept: 'application/json' },
        body: source
      });
    if (response.status >= 400 && response.status < 500) {
      writeStarted = false;
      finish(ctx, id, 'rejected', 'Cloudflare rejected the upload (HTTP ' + response.status + ').');
      throw new Error('Cloudflare rejected the upload (HTTP ' + response.status + '). Check the linked account permissions.');
    }
    const result = await boundedJSON(response, 2000000) as { success?: boolean };
    if (result.success === false) {
      writeStarted = false;
      finish(ctx, id, 'rejected', 'Cloudflare explicitly rejected the upload.');
      throw new Error('Cloudflare explicitly rejected the upload. No automatic retry was made.');
    }
    if (!response.ok || result.success !== true) throw new Error('Upload not confirmed.');
    finish(ctx, id, 'uploaded', 'Cloudflare accepted the new feed. Allow up to six minutes for extension caches.');
    return { changed: true, publicationId: id, feedHash: afterHash, feedUrl: FEED_URL,
      message: 'Uploaded to Cloudflare. Allow up to six minutes for propagation and extension refresh.' };
  } catch (error) {
    if (writeStarted) {
      ctx.sql.exec('UPDATE publications SET state = ?, detail = ? WHERE id = ?',
        'unknown', 'Upload outcome is uncertain. Resolve against the live feed before another write.', id);
      throw new Error('Publication ' + id + ' has an uncertain outcome. Call publication/get and resolvePending; do not repeat the update.');
    }
    ctx.sql.exec('UPDATE publish_lock SET operation_id = NULL, started_at = NULL WHERE operation_id = ?', id);
    throw error;
  }
}

export function publication(ctx: ReadContext | WriteContext, id: string) {
  const rows = ctx.sql.exec<Publication>('SELECT * FROM publications WHERE id = ?', id).toArray();
  if (!rows.length) throw new Error('Publication not found.');
  return rows[0]!;
}
export function publicationSummary(row: Publication) {
  return { id: row.id, state: row.state, action: row.action, beforeHash: row.before_hash,
    afterHash: row.after_hash, startedAt: row.started_at, finishedAt: row.finished_at, detail: row.detail };
}
export function history(ctx: ReadContext, limit: number) {
  return ctx.sql.exec<Omit<Publication, 'before_json' | 'after_json'>>(
    'SELECT id, state, action, before_hash, after_hash, started_at, finished_at, detail FROM publications ORDER BY started_at DESC LIMIT ?', limit)
    .toArray().map(row => ({
      id: row.id, state: row.state, action: row.action, beforeHash: row.before_hash, afterHash: row.after_hash,
      startedAt: row.started_at, finishedAt: row.finished_at, detail: row.detail
    }));
}
export async function resolvePending(ctx: WriteContext, operationId: string) {
  const lock = pendingOperation(ctx);
  if (lock?.id !== operationId) throw new Error('That operation does not hold the publication lock.');
  const rows = ctx.sql.exec<Publication>('SELECT * FROM publications WHERE id = ?', operationId).toArray();
  const row = rows[0];
  if (row?.state !== 'unknown' && Date.now() - (lock.startedAt ?? Date.now()) < 5 * 60 * 1000)
    throw new Error('The operation may still be running. Wait five minutes before recovering an interrupted publication.');
  const liveHash = await feedHash(await readLive(ctx));
  const state = !row ? 'no_upload_started' : liveHash === row.after_hash ? 'uploaded'
    : liveHash === row.before_hash ? 'not_applied' : 'diverged';
  ctx.sql.transaction(() => {
    const current = pendingOperation(ctx);
    if (current?.id !== operationId) throw new Error('Publication lock changed; inspect status again.');
    if (row) ctx.sql.exec('UPDATE publications SET state = ?, finished_at = ?, detail = ? WHERE id = ?',
      state, Date.now(), 'Resolved by reading the live feed; no upload was retried.', operationId);
    ctx.sql.exec('UPDATE publish_lock SET operation_id = NULL, started_at = NULL WHERE operation_id = ?', operationId);
  });
  return { operationId, state, liveHash, message: 'Resolved without replaying the upload. Read the live data before editing again.' };
}
