import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
import { validateRemoteData } from '../src/remote-data.js';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const snapshot = JSON.parse(await read('data/snapshot.json'));
const designSnapshot = JSON.parse(await read('data/design-snapshot.json'));
const config = JSON.parse(await read('data/remote-config.json'));
const feed = validateRemoteData({ ...config, build: snapshot, design: designSnapshot });
const { version } = JSON.parse(await read('package.json'));
const css = await read('src/card.css');
const source = await read('src/content.js');
const bundle = `(() => {\n'use strict';\n${source}\ninstallTriage(${JSON.stringify(snapshot)}, ${JSON.stringify(css)}, ${JSON.stringify(designSnapshot)});\n})();\n`;
const manifest = {
  manifest_version: 3,
  name: 'sdhwex',
  version,
  description: 'Hardware review findings and reasons, automatically refreshed from Cloudflare with an offline fallback.',
  permissions: ['storage'],
  host_permissions: ['https://sdhwex-data.enderium42.workers.dev/*'],
  background: { service_worker: 'background.js', type: 'module' },
  content_security_policy: { extension_pages: "script-src 'self'; object-src 'self'" },
  content_scripts: [{
    matches: ['https://stardance.hackclub.com/*'],
    js: ['content.js'],
    run_at: 'document_idle'
  }]
};
await mkdir(new URL('dist/chrome/', root), { recursive: true });
await writeFile(new URL('dist/chrome/manifest.json', root), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(new URL('dist/chrome/content.js', root), bundle);
for (const file of ['background.js', 'remote-data.js'])
  await copyFile(new URL('src/' + file, root), new URL('dist/chrome/' + file, root));
const metadata = `// ==UserScript==
// @name         sdhwex
// @namespace    local.stardance.build-queue-triage
// @version      ${version}
// @description  Bundled offline hardware-review snapshots. Use the Chrome extension for Cloudflare updates.
// @match        https://stardance.hackclub.com/*
// @run-at       document-idle
// @grant        none
// @noframes
// ==/UserScript==
\n`;
await writeFile(new URL('dist/stardance-triage.user.js', root), metadata + bundle);
await mkdir(new URL('cloudflare/', root), { recursive: true });
await writeFile(new URL('cloudflare/worker.js', root),
  `// Generated by npm run build. Edit data/*.json instead.\nconst TRIAGE_DATA = ${JSON.stringify(feed)};\n` + await read('cloudflare/handler.js'));
await promisify(execFile)('zip', ['-q', '-X', '../sdhwex-chrome.zip',
  'manifest.json', 'content.js', 'background.js', 'remote-data.js'], {
  cwd: fileURLToPath(new URL('dist/chrome/', root))
});
await copyFile(new URL('dist/sdhwex-chrome.zip', root), new URL('dist/stardance-triage-chrome.zip', root));
console.log(`Built sdhwex ${version}: ${snapshot.projects.length} build / ${designSnapshot.projects.length} design projects. Chrome ZIP: dist/sdhwex-chrome.zip`);
